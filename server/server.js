const getSituationsList = () => {
  return Object.values(SITUATIONS).map(sit => ({
    id: sit.id,
    title: sit.title,
    difficulty: sit.metadata.difficulty,
    estimated_time: sit.metadata.estimated_time,
    tags: sit.metadata.tags,
    // ДОБАВЬТЕ недостающие поля:
    description: sit.nodes[sit.initialNode]?.description || "Описание отсутствует",
    type: LIBRARY.problems[sit.problemRef]?.type || "Не указан",
    typeIcon: determineIcon(LIBRARY.problems[sit.problemRef]?.type),
    dataType: determineDataType(LIBRARY.problems[sit.problemRef]?.type)
  }));
};

