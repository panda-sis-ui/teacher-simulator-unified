const determineIcon = (type) => {
  const iconMap = {
    'Мотивационные кризисы': 'lightbulb',
    'Организационные конфликты': 'tasks',
    'Конфликты взаимодействия': 'comments',
    'Внутриличностные конфликты': 'user-injured',
    'Межличностные конфликты': 'user-friends',
    'Личность vs. группа': 'user-shield',
    'Межгрупповые конфликты': 'users'
  };
  return iconMap[type] || 'question-circle';
};

const determineDataType = (type) => {
  const dataTypeMap = {
    'Мотивационные кризисы': 'motivational',
    'Организационные конфликты': 'organizational',
    'Конфликты взаимодействия': 'interaction',
    'Внутриличностные конфликты': 'intrapersonal',
    'Межличностные конфликты': 'interpersonal',
    'Личность vs. группа': 'personal-group',
    'Межгрупповые конфликты': 'intergroup'
  };
  return dataTypeMap[type] || 'general';
};

