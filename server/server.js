app.get('/api/situations/:id', (req, res) => {
  const id = req.params.id;
  console.log(`✅ Запрос ситуации #${id}`);

  const situation = SITUATIONS[id];

  if (situation) {
    res.json(situation);
  } else {
    console.log(`❌ Ситуация #${id} не найдена`);
    res.status(404).json({ error: 'Ситуация не найдена' });
  }
});

// Маршрут 4: Получить конкретный узел ситуации
app.get('/api/situations/:sitId/nodes/:nodeId', (req, res) => {
  const { sitId, nodeId } = req.params;
  console.log(`✅ Запрос узла ${nodeId} ситуации #${sitId}`);

  const situation = SITUATIONS[sitId];

  if (!situation) {
    return res.status(404).json({ error: 'Ситуация не найдена' });
  }

  const node = situation.nodes[nodeId];

  if (node) {
    res.json(node);
  } else {
    console.log(`❌ Узел ${nodeId} не найден в ситуации #${sitId}`);
    res.status(404).json({ error: 'Узел не найден' });
  }
});

